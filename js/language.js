const dictionary = new Map(entries);
const originals = new WeakMap();
const attributeOriginals = new WeakMap();
const storageKey = 'baddini-language';
const attributes = ['aria-label', 'alt', 'title'];
const mediaPrefix = /^((?:The Weirdo) — |Próximo: )(.+?)( ↗)?$/;

let language = 'pt';
try {
  if (localStorage.getItem(storageKey) === 'en') language = 'en';
} catch {}

export function translate(text) {
  if (language !== 'en') return text;
  if (dictionary.has(text)) return dictionary.get(text);
  const parts = text.match(mediaPrefix);
  if (parts) return (parts[1] === 'Próximo: ' ? 'Next: ' : parts[1]) + translate(parts[2]) + (parts[3] || '');
  return text;
}

export function localize(root = document.body) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      return node.parentElement.closest('script, style, .language-switch')
        ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT;
    }
  });
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    if (!originals.has(node)) originals.set(node, node.data);
    const source = originals.get(node);
    const value = source.trim();
    if (value) node.data = source.replace(value, translate(value));
  }
  root.querySelectorAll('a[data-mail-subject]').forEach((link) => {
    const address = link.getAttribute('href').split('?')[0];
    link.href = address + '?subject=' + encodeURIComponent(translate(link.dataset.mailSubject));
  });
  root.querySelectorAll('[aria-label], [alt], [title]').forEach((element) => {
    if (!attributeOriginals.has(element)) {
      attributeOriginals.set(element, Object.fromEntries(attributes.filter((name) => element.hasAttribute(name)).map((name) => [name, element.getAttribute(name)])));
    }
    for (const [name, value] of Object.entries(attributeOriginals.get(element))) element.setAttribute(name, translate(value));
  });
}

const header = document.querySelector('.top');
if (header) {
  const selector = document.createElement('div');
  selector.className = 'language-switch mono';
  selector.setAttribute('role', 'group');
  selector.innerHTML = '<button type="button" data-locale="pt" lang="pt-BR" aria-label="Português">PT</button><button type="button" data-locale="en" lang="en" aria-label="English">EN</button>';
  header.append(selector);
  const updateLanguage = () => {
    document.documentElement.lang = language === 'en' ? 'en' : 'pt-BR';
    selector.setAttribute('aria-label', language === 'en' ? 'Language' : 'Idioma');
    selector.querySelectorAll('button').forEach((button) => {
      button.setAttribute('aria-pressed', String(button.dataset.locale === language));
    });
    localize();
    document.dispatchEvent(new Event('baddini:language'));
  };
  selector.addEventListener('click', (event) => {
    const button = event.target.closest('button');
    if (!button) return;
    language = button.dataset.locale;
    try { localStorage.setItem(storageKey, language); } catch {}
    updateLanguage();
  });
  updateLanguage();
}
